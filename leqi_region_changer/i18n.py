_current_language = DEFAULT_LANGUAGE


def set_language(language: str) -> str:
    """Set and return the active language, falling back to English."""

    global _current_language
    _current_language = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    return _current_language


def get_language() -> str:
    return _current_language


def translate(key: str, **values: object) -> str:
    template = TRANSLATIONS[_current_language][key]
    return template.format(**values)


def language_from_label(label: str) -> str:
    return next(
        (code for code, native_label in LANGUAGE_LABELS.items() if native_label == label),
        DEFAULT_LANGUAGE,
    )
